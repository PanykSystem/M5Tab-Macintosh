#!/usr/bin/env python3
"""Generate icons.r: sun icons for the Brightness Control Strip module.

ics#/ics4/ics8 256-258 are the dim, medium and bright suns drawn in the
Control Strip. The 128 family (ICN#, icl4, icl8, ics#, ics4, ics8) is the
module file's Finder icon. Run with --preview to print them as text.
"""
import sys
from pathlib import Path

# Mac 4-bit and 8-bit system palette indices
C4 = {"white": 0, "yellow": 1, "orange": 2, "lgray": 12, "mgray": 13, "black": 15}
C8 = {"white": 0, "yellow": 5, "orange": 17, "lgray": 247, "mgray": 250, "black": 255}


# 15x15 pixel art on a 16x16 grid: '#' black, 'o' yellow, '-' light gray.
BRIGHT = """
.......#.......
.......#.......
..#....#....#..
...#.......#...
.....#####.....
....#ooooo#....
....#ooooo#....
###.#ooooo#.###
....#ooooo#....
....#ooooo#....
.....#####.....
...#.......#...
..#....#....#..
.......#.......
.......#.......
"""
MEDIUM = """
...............
.......#.......
.......#.......
...#.......#...
.....#####.....
....#ooooo#....
....#ooooo#....
.##.#ooooo#.##.
....#ooooo#....
....#ooooo#....
.....#####.....
...#.......#...
.......#.......
.......#.......
...............
"""
DIM = """
...............
...............
.......#.......
...............
.....#####.....
....#-----#....
....#-----#....
..#.#-----#.#..
....#-----#....
....#-----#....
.....#####.....
...............
.......#.......
...............
...............
"""
NAMES = {".": None, "#": "black", "o": "yellow", "-": "lgray"}


def art(text, scale=1):
    rows = [r for r in text.strip().splitlines()]
    size = 16 * scale
    img = [[None] * size for _ in range(size)]
    for y, row in enumerate(rows):
        for x, ch in enumerate(row):
            for dy in range(scale):
                for dx in range(scale):
                    img[y * scale + dy + (scale // 2)][x * scale + dx + (scale // 2)] = NAMES[ch]
    return img


def bits(img, mask=False):
    size = len(img)
    out = bytearray()
    for row in img:
        v = 0
        for x, px in enumerate(row):
            if px is not None and (mask or px == "black"):
                v |= 1 << (size - 1 - x)
        out += v.to_bytes(size // 8, "big")
    return bytes(out)


def depth4(img):
    out = bytearray()
    for row in img:
        nibbles = [C4[p] if p else 0 for p in row]
        out += bytes((nibbles[i] << 4) | nibbles[i + 1] for i in range(0, len(nibbles), 2))
    return bytes(out)


def depth8(img):
    return bytes(C8[p] if p else 0 for row in img for p in row)


def rez(kind, rid, data):
    lines = [f"data '{kind}' ({rid}, purgeable) {{"]
    for i in range(0, len(data), 16):
        lines.append(f'    $"{data[i:i+16].hex().upper()}"')
    lines.append("};")
    return "\n".join(lines)


def family(img, rid, small):
    one_bit = bits(img) + bits(img, mask=True)
    if small:
        return [rez("ics#", rid, one_bit), rez("ics4", rid, depth4(img)), rez("ics8", rid, depth8(img))]
    return [rez("ICN#", rid, one_bit), rez("icl4", rid, depth4(img)), rez("icl8", rid, depth8(img))]


def main():
    strip = [art(DIM), art(MEDIUM), art(BRIGHT)]
    finder_small = art(BRIGHT)
    finder_large = art(BRIGHT, scale=2)

    if "--preview" in sys.argv:
        for img in strip + [finder_large]:
            for row in img:
                print("".join({None: ".", "black": "#", "yellow": "o", "lgray": "-"}.get(p, "?") for p in row))
            print()
        return

    parts = ["/* Generated by make_icons.py; do not edit. */", ""]
    for i, img in enumerate(strip):
        parts += family(img, 256 + i, small=True)
    parts += family(finder_large, 128, small=False)
    parts += family(finder_small, 128, small=True)
    Path(__file__).with_name("icons.r").write_text("\n".join(parts) + "\n")


if __name__ == "__main__":
    main()
